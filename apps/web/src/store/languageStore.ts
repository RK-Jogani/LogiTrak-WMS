export const useLanguageStore = create<LanguageState>()(
  persist(
    (set, get) => ({
      language: "en",
      setLanguage: (lang: Language) => set({ language: lang }),
      t: (key: string) => {
        const lang = get().language;
        return translations[lang]?.[key] || translations["en"]?.[key] || key;
      },
    }),
    {
      name: "logitrack-language-setting",
    }
  )
);
